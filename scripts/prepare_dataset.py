"""把人工复核后的 data/autolabel/ 切分成 YOLO 训练集 data/yolo_dataset/。

在 labelImg/Roboflow 里复核改完标注后跑这个，它会：
  - 读 data/autolabel/{images,labels,classes.txt}
  - 跳过空标签图（没框=没目标，默认不进训练集，避免误当负样本）
  - 打乱 + 70/20/10 切 train/val/test
  - 写出 data/yolo_dataset/{images,labels}/{train,val,test} + data.yaml

然后即可：python scripts/train_yolo.py
"""
import random
import shutil
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parent
SRC = PROJECT_ROOT / "data" / "training" / "autolabel"
OUT = PROJECT_ROOT / "data" / "training" / "yolo_dataset"
BG_DIR = PROJECT_ROOT / "data" / "training" / "photo" / "背景图"  # 纯背景图：作为空标签负样本喂入，降误检
SPLIT = (0.7, 0.2, 0.1)
KEEP_EMPTY = False   # True 则把"自动标注没框到目标"的空标签图也当负样本（一般 False，背景另行接入）
ADD_BACKGROUND = True  # 把 BG_DIR 的背景图作为负样本（空标签）加入训练集
# AUTO_ONLY=True：只用自动标注里"信心高"的 AUTO（排除 review_list 里的 REVIEW/multi），
# 跳过人工复核直接训一个基线模型。复核完想用全部时改成 False。
AUTO_ONLY = True

random.seed(42)


def load_review_stems():
    """review_list.txt 里列出的 REVIEW/multi 图（去掉扩展名），AUTO_ONLY 时排除它们"""
    rl = SRC / "review_list.txt"
    if not rl.exists():
        return set()
    stems = set()
    for line in rl.read_text(encoding="utf-8").splitlines():
        name = line.strip().split()[0] if line.strip() else ""
        if name.endswith(".jpg"):
            stems.add(name[:-4])
    return stems


def main():
    imgs_dir = SRC / "images"
    lbls_dir = SRC / "labels"
    classes = (SRC / "classes.txt").read_text(encoding="utf-8").split()
    if not imgs_dir.exists():
        raise FileNotFoundError(f"找不到 {imgs_dir}，先跑 scripts/sam_autolabel.py 并复核")

    review = load_review_stems() if AUTO_ONLY else set()

    pairs, empty, skipped_review = [], 0, 0
    for img in sorted(imgs_dir.glob("*.jpg")):
        if AUTO_ONLY and img.stem in review:
            skipped_review += 1
            continue
        lbl = lbls_dir / f"{img.stem}.txt"
        text = lbl.read_text(encoding="utf-8").strip() if lbl.exists() else ""
        if not text:
            empty += 1
            if not KEEP_EMPTY:
                continue
        pairs.append((img, lbl if text else None))

    # 合并人工标注的多工具图（data/label_multi）：只收"非空 且 含非0类别"的，
    # 自动跳过占位(全0)和空文件——即用户跳过的重复图。
    multi_added, multi_skipped = 0, 0
    # 自动合并所有 data/label_* 批次（label_multi / label_new / label_new2 / ...）
    for multi_dir in sorted((PROJECT_ROOT / "data" / "training").glob("label_*")):
        if not (multi_dir / "labels").is_dir():
            continue
        for lbl in sorted((multi_dir / "labels").glob("*.txt")):
            if lbl.name == "classes.txt":
                continue
            text = lbl.read_text(encoding="utf-8").strip()
            classes_in = {ln.split()[0] for ln in text.splitlines() if ln.strip()}
            if not classes_in or classes_in == {"0"}:   # 空 或 纯占位0 → 跳过
                multi_skipped += 1
                continue
            img = multi_dir / "images" / f"{lbl.stem}.jpg"
            if img.exists():
                pairs.append((img, lbl))
                multi_added += 1

    # 背景图：纯负样本（空标签）。YOLO 用空标签图学"这里没有任何目标"，能压低误检。
    bg_added = 0
    if ADD_BACKGROUND and BG_DIR.is_dir():
        for img in sorted(BG_DIR.iterdir()):
            if img.suffix.lower() in {".jpg", ".jpeg", ".png", ".bmp"}:
                pairs.append((img, None))   # None → 写空标签
                bg_added += 1

    print(f"📋 {len(classes)} 类: {classes}")
    if bg_added:
        print(f"🖼️  背景负样本: {bg_added} 张（空标签）")
    if AUTO_ONLY:
        print(f"⚙️  AUTO_ONLY 模式：排除 {skipped_review} 张 REVIEW，只用高信心 AUTO")
    print(f"➕ 合并多工具人工标注: {multi_added} 张（跳过占位/空 {multi_skipped} 张）")
    print(f"📦 有效标注图: {len(pairs)}（跳过空标签 {empty} 张）" if not KEEP_EMPTY
          else f"📦 总图: {len(pairs)}（含空标签负样本 {empty} 张）")
    if not pairs:
        raise RuntimeError("没有任何有效标注，检查是否已复核标注")

    random.shuffle(pairs)
    n = len(pairs)
    n_tr = int(n * SPLIT[0])
    n_va = int(n * SPLIT[1])
    splits = {"train": pairs[:n_tr], "val": pairs[n_tr:n_tr + n_va], "test": pairs[n_tr + n_va:]}

    if OUT.exists():
        shutil.rmtree(OUT)
    for s in splits:
        (OUT / "images" / s).mkdir(parents=True, exist_ok=True)
        (OUT / "labels" / s).mkdir(parents=True, exist_ok=True)

    for s, items in splits.items():
        for img, lbl in items:
            shutil.copy(img, OUT / "images" / s / img.name)
            dst = OUT / "labels" / s / f"{img.stem}.txt"
            if lbl is not None:
                shutil.copy(lbl, dst)
            else:
                dst.write_text("", encoding="utf-8")   # 负样本：空标签
        print(f"  {s}: {len(items)} 张")

    (OUT / "data.yaml").write_text(
        "# Auto-generated by scripts/prepare_dataset.py\n"
        f"path: {OUT.resolve().as_posix()}\n"
        "train: images/train\nval: images/val\ntest: images/test\n\n"
        f"nc: {len(classes)}\nnames: {classes}\n",
        encoding="utf-8")
    print(f"\n✅ data.yaml 已生成: {OUT/'data.yaml'}")
    print("   下一步: python scripts/train_yolo.py")


if __name__ == "__main__":
    main()
